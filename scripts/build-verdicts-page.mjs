#!/usr/bin/env node
/**
 * Builds __docs__/verdicts.mdx from verdicts/verdicts.json and verdicts/follow-ups.json.
 *
 * Why generated: @storybook/addon-mcp's get-documentation returns the MDX file's
 * source verbatim. JSX that maps over imported JSON reaches MCP clients as code,
 * not as rulings. So every ruling is written into the page as literal markdown,
 * and the raw files go in fenced blocks for tools to parse.
 *
 *   node scripts/build-verdicts-page.mjs          write the page
 *   node scripts/build-verdicts-page.mjs --check  exit 1 if the page is out of date (CI)
 */
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VERDICTS = "verdicts/verdicts.json";
const FOLLOW_UPS = "verdicts/follow-ups.json";
const OUT = "__docs__/verdicts.mdx";
const TITLE = "Design Guidelines / Verdicts";

const VERDICT_LABELS = {
    "not-an-issue": "Not an issue",
    "wb-gap": "Wonder Blocks gap",
    drift: "Drift",
    "exemption-approved": "Exemption approved",
    "exemption-denied": "Exemption denied",
};

// Escape characters MDX would read as JSX or expressions, outside inline code spans.
function prose(text) {
    if (text == null) return "";
    return String(text)
        .split(/(`+[^`]*?`+)/g)
        .map((part, i) =>
            i % 2 ? part : part.replace(/([{}<>\\])/g, "\\$1").replace(/\s*\n\s*/g, " "),
        )
        .join("");
}

const code = (s) => "`" + String(s).replace(/`/g, "") + "`";
const link = (label, url) => (url ? `[${prose(label)}](${url})` : prose(label));

function fence(info, body) {
    const longest = Math.max(2, ...(body.match(/`+/g) ?? []).map((m) => m.length));
    const ticks = "`".repeat(longest + 1);
    return `${ticks}${info}\n${body.replace(/\n$/, "")}\n${ticks}`;
}

function verdictLabel(e) {
    if (e.verdict === "delta" && e.kind) return VERDICT_LABELS[e.kind] ?? e.kind;
    return VERDICT_LABELS[e.verdict] ?? e.verdict;
}

function describeMatch(m = {}) {
    const parts = [];
    if (m.component) parts.push(`${code(m.component)}${m.kind === "wb-override" ? " (style override)" : ""}`);
    if (m.uses_wb) parts.push(`uses WB ${code(m.uses_wb)}`);
    if (m.file) parts.push(`in ${code(m.file)}`);
    if (m.shared_style) parts.push(`shared style ${code(m.shared_style)}`);
    if (m.local_styles?.length) parts.push(`local styles ${m.local_styles.map(code).join(", ")}`);
    return parts.join(" · ") || "—";
}

function isApplied(e, rulers) {
    return e.status === "confirmed" && rulers.includes(e.approved_by);
}

function verdictSection(e, followUps) {
    const lines = [`### ${e.id} · ${verdictLabel(e)}${e.title ? ` — ${prose(e.title)}` : ""}`, ""];
    const item = (label, value) => value && lines.push(`- **${label}:** ${value}`);

    item("Applies to", describeMatch(e.match));
    item("Ruling", link(e.ruling_text ?? e.ruling, e.ruling_link));
    item("Reason", prose(e.reason ?? e.ruling));
    item("In prod", prose(e.prod));
    item("What to do", prose(e.suggested_wb));
    item(
        "Ruled by",
        e.approved_by &&
            `${prose(e.approved_by)}${e.approved_at ? ` on ${e.approved_at}` : ""}` +
                (e.requested_by ? ` (requested by ${prose(e.requested_by)})` : ""),
    );

    if (e.guideline_link) item("Guideline", link(e.guideline ?? "Guideline", e.guideline_link));
    else if (e.guideline) item("Guideline", prose(e.guideline));
    else item("Guideline", e.missing_guidance ? "None yet" : "None needed");
    if (e.missing_guidance) item("Guidance needed", prose(e.guidance_needed));

    for (const q of e.quality_issues ?? []) {
        item(
            `Separate ${q.kind ?? "quality"} issue`,
            `${prose(q.summary)}${q.owner ? ` (owner: ${prose(q.owner)})` : ""}${q.decision ? `. ${prose(q.decision)}` : ""}`,
        );
    }
    const mine = followUps.filter((f) => f.verdict === e.id).map((f) => f.id);
    item("Follow-ups", mine.join(", "));
    return lines.join("\n");
}

export async function build() {
    const [verdictsRaw, followUpsRaw] = await Promise.all(
        [VERDICTS, FOLLOW_UPS].map((p) => readFile(path.join(root, p), "utf-8")),
    );
    const data = JSON.parse(verdictsRaw);
    const followUps = JSON.parse(followUpsRaw).follow_ups ?? [];
    const rulers = data.rulers ?? [];
    const entries = data.entries ?? [];
    const applied = entries.filter((e) => isApplied(e, rulers));
    const pending = entries.filter((e) => !isApplied(e, rulers));
    const missing = applied.filter((e) => e.missing_guidance);

    const out = [
        `import {Meta} from "@storybook/addon-docs/blocks";`,
        "",
        `<Meta title="${TITLE}" />`,
        "",
        `{/* Generated by scripts/build-verdicts-page.mjs from ${VERDICTS} and ${FOLLOW_UPS}. Don't edit by hand: change the JSON and run \`pnpm verdicts:page\`. */}`,
        "",
        "# Verdicts",
        "",
        `${prose(data.owner ?? "Design Infra")}'s rulings on how Wonder Blocks is meant to be used (Judge Trudy). ` +
            `Each ruling is tied to a component in code. The prototype builder's audit applies them, so every prototype gets the same answer.`,
        "",
        `**Rulers:** ${rulers.map(prose).join(", ")}. **Requests:** ${prose(data.channel ?? "#design-infra")}. ` +
            `A ruling is a thread reply that starts with ${code("Ruling:")}, and it counts once it's merged into ${code(VERDICTS)}.`,
        "",
        `## Rulings (${applied.length})`,
        "",
        applied.length ? applied.map((e) => verdictSection(e, followUps)).join("\n\n") : "No rulings yet.",
        "",
        `## Missing guidance (${missing.length})`,
        "",
        missing.length
            ? "Rulings that stand in for a guideline that doesn't exist yet.\n\n" +
              missing.map((e) => `- **${e.id}:** ${prose(e.guidance_needed ?? e.title ?? e.reason)}`).join("\n")
            : "None.",
        "",
        `## Follow-ups (${followUps.length})`,
        "",
        followUps.length
            ? followUps
                  .map(
                      (f) =>
                          `- **${f.id}** (${prose(f.type)}, ${prose(f.status)}${f.owner ? `, ${prose(f.owner)}` : ""}${f.jira_key ? `, ${f.jira_key}` : ""}, from ${f.verdict}): ${prose(f.summary)}`,
                  )
                  .join("\n")
            : "None.",
    ];

    if (pending.length) {
        out.push(
            "",
            `## Not applied (${pending.length})`,
            "",
            "In the file but not confirmed by a ruler, so the audit ignores them.",
            "",
            pending.map((e) => `- **${e.id}** (${prose(e.status ?? "no status")}): ${verdictLabel(e)}, ${describeMatch(e.match)}`).join("\n"),
        );
    }

    out.push(
        "",
        "## Raw data",
        "",
        `The files exactly as committed. Tools reading this page over the design-guidelines connection should parse these blocks, not the text above.`,
        "",
        fence("json verdicts.json", verdictsRaw),
        "",
        fence("json follow-ups.json", followUpsRaw),
        "",
    );
    return out.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const page = await build();
    const target = path.join(root, OUT);
    if (process.argv.includes("--check")) {
        const current = await readFile(target, "utf-8").catch(() => "");
        if (current !== page) {
            console.error(`${OUT} is out of date with ${VERDICTS}. Run: pnpm verdicts:page`);
            process.exit(1);
        }
        console.log(`${OUT} is up to date.`);
    } else {
        await writeFile(target, page);
        console.log(`Wrote ${OUT}`);
    }
}
